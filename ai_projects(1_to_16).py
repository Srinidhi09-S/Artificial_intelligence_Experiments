    add("Fill 3-litre container", a, CAP_B)

    # Empty either container
    add("Empty 4-litre container", 0, b)
    add("Empty 3-litre container", a, 0)

    # Pour from 4-litre container into 3-litre container
    transfer = min(a, CAP_B - b)
    add("Pour 4L into 3L", a - transfer, b + transfer)

    # Pour from 3-litre container into 4-litre container
    transfer = min(b, CAP_A - a)
    add("Pour 3L into 4L", a + transfer, b - transfer)

    return next_states



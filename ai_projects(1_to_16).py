# Experiment 5: 8-Queens Problem Using Backtracking

N = 8
board = [-1] * N
placement_attempts = 0
backtracks = 0


# Check whether a queen can be placed safely
def is_safe(row, col):
    for prev_row in range(row):
        prev_col = board[prev_row]

        # Check same column and diagonal conflicts
        if prev_col == col:
            return False

        if abs(prev_col - col) == abs(prev_row - row):
            return False

    return True


# Solve using recursive backtracking
def solve(row):
    global placement_attempts, backtracks

    # All eight queens have been placed
    if row == N:
        return True

    # Try every column in the current row
    for col in range(N):
        placement_attempts += 1

        if is_safe(row, col):
            board[row] = col

            if solve(row + 1):
                return True

            # Undo the placement and try another column
            board[row] = -1
            backtracks += 1

    return False


# Display the chessboard
def display_board():
    print("\nFinal Chessboard:")
    print("  " + " ".join(str(c + 1) for c in range(N)))

    for row in range(N):
        print(row + 1, end=" ")
        for col in range(N):
            if board[row] == col:
                print("Q", end=" ")
            else:
                print(".", end=" ")
        print()


# Execute the program

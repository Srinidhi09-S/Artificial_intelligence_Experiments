def a_star(start, goal):
    # Priority queue stores (f, g, node)
    open_list = [(heuristic[start], 0, start)]

    # Lowest known cost from start to each node
    g_cost = {start: 0}

    # Parent pointers for reconstructing the route
    parent = {start: None}

    # Nodes whose expansion is reported
    expanded = []

    while open_list:
        f, g, current = heapq.heappop(open_list)

        # Ignore outdated queue entries
        if g != g_cost.get(current):
            continue

        expanded.append(current)
        print(
            f"Expanding {current}: "
            f"g(n)={g}, h(n)={heuristic[current]}, f(n)={f}"
        )

        # Goal test
        if current == goal:
            path = []
            node = goal

            while node is not None:
                path.append(node)
                node = parent[node]

            path.reverse()

            print("\nOptimal route:", " -> ".join(path))
            print("Total path cost:", g_cost[goal])
            print("Expansion order:", " -> ".join(expanded))
            return path, g_cost[goal], expanded

        # Explore neighbouring locations
        for neighbour, cost in graph[current].items():
            new_g = g_cost[current] + cost

            if new_g < g_cost.get(neighbour, float('inf')):
                g_cost[neighbour] = new_g
                parent[neighbour] = current
                new_f = new_g + heuristic[neighbour]

                heapq.heappush(
                    open_list, (new_f, new_g, neighbour)
                )

    print("No route exists.")
    return None, float('inf'), expanded


